-- Operational login identity and single-salon membership.
-- Run as atendee_migrator on a fresh database after roles template 001.
-- This does not create platform administrator identities.
\set ON_ERROR_STOP on
BEGIN;

SET LOCAL ROLE atendee_identity_owner;

CREATE TABLE identity."AspNetUsers"
(
    "Id" UUID NOT NULL,
    "UserName" VARCHAR(256),
    "NormalizedUserName" VARCHAR(256),
    "Email" VARCHAR(256),
    "NormalizedEmail" VARCHAR(256),
    "EmailConfirmed" BOOLEAN NOT NULL,
    "PasswordHash" TEXT,
    "SecurityStamp" TEXT,
    "ConcurrencyStamp" TEXT,
    "PhoneNumber" TEXT,
    "PhoneNumberConfirmed" BOOLEAN NOT NULL,
    "TwoFactorEnabled" BOOLEAN NOT NULL,
    "LockoutEnd" TIMESTAMPTZ,
    "LockoutEnabled" BOOLEAN NOT NULL,
    "AccessFailedCount" INTEGER NOT NULL,
    CONSTRAINT "PK_AspNetUsers" PRIMARY KEY ("Id")
);

CREATE UNIQUE INDEX "UserNameIndex"
    ON identity."AspNetUsers" ("NormalizedUserName")
    WHERE "NormalizedUserName" IS NOT NULL;

CREATE UNIQUE INDEX "EmailIndex"
    ON identity."AspNetUsers" ("NormalizedEmail")
    WHERE "NormalizedEmail" IS NOT NULL;

CREATE TABLE identity."AspNetUserClaims"
(
    "Id" INTEGER GENERATED BY DEFAULT AS IDENTITY,
    "UserId" UUID NOT NULL,
    "ClaimType" TEXT,
    "ClaimValue" TEXT,
    CONSTRAINT "PK_AspNetUserClaims" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_AspNetUserClaims_AspNetUsers_UserId"
        FOREIGN KEY ("UserId") REFERENCES identity."AspNetUsers" ("Id") ON DELETE CASCADE
);

CREATE INDEX "IX_AspNetUserClaims_UserId"
    ON identity."AspNetUserClaims" ("UserId");

CREATE TABLE identity."AspNetUserLogins"
(
    "LoginProvider" VARCHAR(128) NOT NULL,
    "ProviderKey" VARCHAR(128) NOT NULL,
    "ProviderDisplayName" TEXT,
    "UserId" UUID NOT NULL,
    CONSTRAINT "PK_AspNetUserLogins" PRIMARY KEY ("LoginProvider", "ProviderKey"),
    CONSTRAINT "FK_AspNetUserLogins_AspNetUsers_UserId"
        FOREIGN KEY ("UserId") REFERENCES identity."AspNetUsers" ("Id") ON DELETE CASCADE
);

CREATE INDEX "IX_AspNetUserLogins_UserId"
    ON identity."AspNetUserLogins" ("UserId");

CREATE TABLE identity."AspNetUserTokens"
(
    "UserId" UUID NOT NULL,
    "LoginProvider" VARCHAR(128) NOT NULL,
    "Name" VARCHAR(128) NOT NULL,
    "Value" TEXT,
    CONSTRAINT "PK_AspNetUserTokens"
        PRIMARY KEY ("UserId", "LoginProvider", "Name"),
    CONSTRAINT "FK_AspNetUserTokens_AspNetUsers_UserId"
        FOREIGN KEY ("UserId") REFERENCES identity."AspNetUsers" ("Id") ON DELETE CASCADE
);

-- Kept outside AspNetUsers so ordinary Identity updates cannot roll back a
-- TOTP replay marker. A single UPDATE with a monotonic predicate is atomic.
CREATE TABLE identity."TotpReplayGuards"
(
    "UserId" UUID NOT NULL,
    "LastAcceptedStep" BIGINT,
    CONSTRAINT "PK_TotpReplayGuards" PRIMARY KEY ("UserId"),
    CONSTRAINT "FK_TotpReplayGuards_AspNetUsers_UserId"
        FOREIGN KEY ("UserId") REFERENCES identity."AspNetUsers" ("Id") ON DELETE CASCADE
);

GRANT REFERENCES ON TABLE identity."AspNetUsers" TO atendee_owner;
GRANT USAGE ON SCHEMA identity TO atendee_owner;
RESET ROLE;

SET LOCAL ROLE atendee_owner;

CREATE TABLE atendee.tenants
(
    id UUID NOT NULL,
    name VARCHAR(120) NOT NULL,
    slug VARCHAR(60) NOT NULL,
    time_zone_id VARCHAR(128) NOT NULL,
    status SMALLINT NOT NULL,
    created_at_utc TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_tenants PRIMARY KEY (id),
    CONSTRAINT uq_tenants_slug UNIQUE (slug),
    CONSTRAINT ck_tenants_status CHECK (status BETWEEN 0 AND 7),
    CONSTRAINT ck_tenants_name_nonempty CHECK (length(btrim(name)) > 0),
    CONSTRAINT ck_tenants_slug_nonempty CHECK (length(btrim(slug)) > 0)
);

CREATE TABLE atendee.tenant_users
(
    tenant_id UUID NOT NULL,
    identity_user_id UUID NOT NULL,
    display_name VARCHAR(120) NOT NULL,
    role SMALLINT NOT NULL,
    is_active BOOLEAN NOT NULL,
    created_at_utc TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_tenant_users PRIMARY KEY (tenant_id, identity_user_id),
    CONSTRAINT uq_tenant_users_identity UNIQUE (identity_user_id),
    CONSTRAINT fk_tenant_users_tenant
        FOREIGN KEY (tenant_id) REFERENCES atendee.tenants (id) ON DELETE RESTRICT,
    CONSTRAINT fk_tenant_users_identity
        FOREIGN KEY (identity_user_id) REFERENCES identity."AspNetUsers" ("Id") ON DELETE RESTRICT,
    CONSTRAINT ck_tenant_users_role CHECK (role BETWEEN 1 AND 4),
    CONSTRAINT ck_tenant_users_display_name_nonempty CHECK (length(btrim(display_name)) > 0)
);

CREATE INDEX ix_tenant_users_tenant_active
    ON atendee.tenant_users (tenant_id, is_active, role);

ALTER TABLE atendee.tenant_users ENABLE ROW LEVEL SECURITY;
ALTER TABLE atendee.tenant_users FORCE ROW LEVEL SECURITY;

CREATE POLICY tenant_users_runtime_isolation
ON atendee.tenant_users
FOR ALL
TO atendee_runtime
USING (
    tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::UUID
)
WITH CHECK (
    tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::UUID
);

-- Only the dedicated NOLOGIN owner used by tightly scoped SECURITY DEFINER
-- functions and migrations can see all tenant memberships.
CREATE POLICY tenant_users_owner_access
ON atendee.tenant_users
FOR ALL
TO atendee_owner
USING (true)
WITH CHECK (true);

CREATE FUNCTION atendee.resolve_tenant_membership()
RETURNS TABLE
(
    identity_user_id UUID,
    tenant_id UUID,
    display_name VARCHAR(120),
    role INTEGER,
    is_active BOOLEAN,
    tenant_status INTEGER
)
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, atendee
AS $function$
    SELECT
        membership.identity_user_id,
        membership.tenant_id,
        membership.display_name,
        membership.role::INTEGER,
        membership.is_active,
        tenant.status::INTEGER
    FROM atendee.tenant_users AS membership
    INNER JOIN atendee.tenants AS tenant
        ON tenant.id = membership.tenant_id
    WHERE membership.identity_user_id =
        NULLIF(current_setting('app.identity_user_id', true), '')::UUID;
$function$;

REVOKE ALL ON FUNCTION atendee.resolve_tenant_membership() FROM PUBLIC;
GRANT USAGE ON SCHEMA atendee TO atendee_auth_login;
GRANT EXECUTE ON FUNCTION atendee.resolve_tenant_membership() TO atendee_auth_login;

RESET ROLE;
COMMIT;

-- The auth login has no direct SELECT/UPDATE privileges on atendee.tenant_users
-- or atendee.tenants. It can obtain only the current user's single membership
-- through the fixed SECURITY DEFINER projection above.
